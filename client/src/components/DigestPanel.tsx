import React, { useState, useEffect } from 'react';
import { 
  OrbitState, 
  DigestPerson, 
  DigestResponse 
} from '../types';
import { 
  FileText, 
  Copy, 
  Check, 
  Sparkles, 
  X, 
  AlertTriangle, 
  Calendar, 
  CheckCircle2, 
  RefreshCw, 
  User,
  ExternalLink
} from 'lucide-react';
import { soundEffects } from '../utils/audio';

interface DigestPanelProps {
  isOpen: boolean;
  onClose: () => void;
  state: OrbitState;
  onSelectDecisionById: (id: string) => void;
}

export const DigestPanel: React.FC<DigestPanelProps> = ({
  isOpen,
  onClose,
  state,
  onSelectDecisionById
}) => {
  const [digest, setDigest] = useState<DigestResponse | null>(null);
  const [isLoading, setIsLoading] = useState(false);
  const [copiedPersonName, setCopiedPersonName] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  // Fetch or refresh weekly digest from backend
  const fetchDigest = async () => {
    setIsLoading(true);
    setError(null);
    try {
      const res = await fetch('/api/digest', { method: 'POST' });
      if (!res.ok) throw new Error('Failed to retrieve executive digest');
      const data: DigestResponse = await res.json();
      setDigest(data);
    } catch (err: any) {
      console.warn('Digest load warning:', err);
      setError(err.message || 'Could not assemble weekly digest');
    } finally {
      setIsLoading(false);
    }
  };

  useEffect(() => {
    if (isOpen) {
      fetchDigest();
    }
  }, [isOpen]);

  if (!isOpen) return null;

  // Format single person's card for Slack / Email copying
  const formatSlackEmailDigest = (person: DigestPerson): string => {
    const lines: string[] = [
      `📋 *ORBIT WEEKLY DIGEST // ${person.name.toUpperCase()}*`,
      `━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━`,
      `💡 *EXECUTIVE BRIEF*:`,
      `> ${person.aiSummary}`,
      ``
    ];

    if (person.conflicts.length > 0) {
      lines.push(`⚡ *ACTIVE DECISION CONFLICTS (${person.conflicts.length})*:`);
      person.conflicts.forEach((c: any) => {
        lines.push(`• ⚠ [${c.id}] Contradicts ${c.partnerId}: ${c.description}`);
      });
      lines.push(``);
    }

    if (person.decisions.length > 0) {
      lines.push(`🧠 *DECISIONS RATIFIED (${person.decisions.length})*:`);
      person.decisions.forEach((d: any) => {
        lines.push(`• [${d.id}] "${d.text}" (${d.meetingTitle}) [${d.status.toUpperCase()}]`);
      });
      lines.push(``);
    }

    if (person.openTasks.length > 0) {
      lines.push(`🎯 *ACTIVE ACTION ITEMS (${person.openTasks.length})*:`);
      person.openTasks.forEach((t: any) => {
        const link = t.trackerUrl ? ` — ${t.trackerUrl}` : '';
        lines.push(`• [${t.id}] ${t.task} (Deadline: ${t.deadline}) [${t.status.toUpperCase()}]${link}`);
      });
      lines.push(``);
    }

    lines.push(`━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━`);
    lines.push(`*Generated by ORBIT // Meetings That Remember*`);
    return lines.join('\n');
  };

  const handleCopyText = async (person: DigestPerson) => {
    const text = formatSlackEmailDigest(person);
    try {
      await navigator.clipboard.writeText(text);
      soundEffects.click();
      setCopiedPersonName(person.name);
      setTimeout(() => setCopiedPersonName(null), 2200);
    } catch {
      // Fallback
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-space-950/80 backdrop-blur-md animate-fade-in">
      <div className="relative w-full max-w-4xl max-h-[88vh] flex flex-col hud-panel rounded-xl overflow-hidden border border-sky-500/30 shadow-2xl">
        
        {/* Header Strip */}
        <div className="px-5 py-4 border-b border-sky-500/20 bg-space-900/90 flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="p-2 rounded-lg bg-sky-950/80 border border-sky-500/30 text-sky-400">
              <Sparkles className="w-5 h-5 animate-pulse text-amber-400" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h2 className="font-mono text-sm font-bold tracking-widest text-slate-100 uppercase">
                  WEEKLY EXECUTIVE DIGEST // ROSTER BRIEFING
                </h2>
                {digest?.cached && (
                  <span className="text-[10px] font-mono px-2 py-0.5 rounded bg-sky-950 text-sky-400 border border-sky-500/30">
                    MEMORY CACHED
                  </span>
                )}
              </div>
              <p className="text-xs font-mono text-slate-400 mt-0.5">
                Individualized intelligence briefs, decision commitments, open obligations, and conflict audits
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={() => { soundEffects.click(); fetchDigest(); }}
              disabled={isLoading}
              className="p-1.5 rounded-lg hover:bg-slate-800 text-slate-400 hover:text-sky-400 transition-colors"
              title="Refresh AI Digest"
            >
              <RefreshCw className={`w-4 h-4 ${isLoading ? 'animate-spin text-sky-400' : ''}`} />
            </button>
            <button
              onClick={() => { soundEffects.click(); onClose(); }}
              className="p-1.5 rounded-lg hover:bg-slate-800 text-slate-400 hover:text-white transition-colors"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Content Body */}
        <div className="flex-1 overflow-y-auto p-5">
          {isLoading && !digest ? (
            <div className="py-20 flex flex-col items-center justify-center gap-3 text-center">
              <RefreshCw className="w-8 h-8 text-sky-400 animate-spin" />
              <p className="font-mono text-xs text-sky-300">
                SYNTHESIZING EXECUTIVE BRIEFINGS ACROSS ROSTER...
              </p>
            </div>
          ) : error ? (
            <div className="py-12 text-center text-rose-400 font-mono text-xs">
              {error}
            </div>
          ) : !digest?.people?.length ? (
            <div className="py-12 text-center text-slate-500 font-mono text-xs">
              NO ROSTER COMMITMENTS RECORDED YET
            </div>
          ) : (
            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
              {digest.people.map((person: DigestPerson) => {
                const isCopied = copiedPersonName === person.name;

                return (
                  <div
                    key={person.name}
                    className="p-4 rounded-lg bg-space-900/60 border border-sky-500/20 flex flex-col justify-between hover:border-sky-500/40 transition-colors shadow-lg"
                  >
                    <div>
                      {/* Person Title & Avatar */}
                      <div className="flex items-start justify-between gap-3 pb-3 border-b border-slate-800/80">
                        <div className="flex items-center gap-2.5">
                          <div className="w-8 h-8 rounded-full bg-sky-950 border border-sky-500/40 flex items-center justify-center font-mono font-bold text-xs text-sky-300">
                            {person.initials}
                          </div>
                          <div>
                            <h3 className="font-mono font-bold text-sm text-slate-100">
                              {person.name}
                            </h3>
                            <span className="text-[10px] font-mono text-slate-400">
                              {person.decisions.length} Decisions · {person.openTasks.length} Open Tasks
                            </span>
                          </div>
                        </div>

                        {/* Copy for Slack/Email button */}
                        <button
                          onClick={() => handleCopyText(person)}
                          className={`px-2.5 py-1 rounded text-[11px] font-mono flex items-center gap-1.5 transition-colors border ${
                            isCopied
                              ? 'bg-emerald-950 text-emerald-300 border-emerald-500/40'
                              : 'bg-space-950 hover:bg-sky-950 text-slate-300 hover:text-sky-300 border-slate-700'
                          }`}
                          title="Copy formatted markdown text for Slack or Email"
                        >
                          {isCopied ? (
                            <>
                              <Check className="w-3 h-3 text-emerald-400" />
                              <span>COPIED</span>
                            </>
                          ) : (
                            <>
                              <Copy className="w-3 h-3" />
                              <span>COPY AS TEXT</span>
                            </>
                          )}
                        </button>
                      </div>

                      {/* AI One-Line Summary */}
                      <div className="my-3 p-2.5 rounded bg-sky-950/40 border border-sky-500/30 flex items-start gap-2 text-xs">
                        <Sparkles className="w-4 h-4 text-amber-400 flex-shrink-0 mt-0.5" />
                        <p className="font-sans text-sky-200 leading-snug">
                          {person.aiSummary}
                        </p>
                      </div>

                      {/* Active Conflicts (if any) */}
                      {person.conflicts.length > 0 && (
                        <div className="mb-3 space-y-1.5">
                          <div className="flex items-center gap-1.5 text-[11px] font-mono text-rose-400 font-semibold">
                            <AlertTriangle className="w-3.5 h-3.5 animate-pulse" />
                            <span>ACTIVE CONFLICTS ({person.conflicts.length})</span>
                          </div>
                          {person.conflicts.map((c: any) => (
                            <div key={c.id} className="p-2 rounded bg-rose-950/30 border border-rose-500/40 text-[11px] font-mono text-rose-200">
                              <span className="font-bold text-rose-300">[{c.id} vs {c.partnerId}]:</span> {c.description}
                            </div>
                          ))}
                        </div>
                      )}

                      {/* Decisions Section */}
                      {person.decisions.length > 0 && (
                        <div className="mb-3">
                          <span className="text-[10px] font-mono uppercase tracking-wider text-slate-400 block mb-1">
                            Ratified Decisions ({person.decisions.length})
                          </span>
                          <div className="space-y-1 max-h-24 overflow-y-auto pr-1">
                            {person.decisions.map((d: any) => (
                              <button
                                key={d.id}
                                onClick={() => {
                                  onSelectDecisionById(d.id);
                                  onClose();
                                }}
                                className="w-full text-left p-1.5 rounded bg-space-950/60 hover:bg-space-950 text-[11px] font-sans text-slate-300 hover:text-sky-300 flex items-center justify-between gap-2 border border-slate-800 transition-colors"
                              >
                                <span className="line-clamp-1">⭐ {d.text}</span>
                                <span className="text-[9px] font-mono uppercase text-sky-400 flex-shrink-0">
                                  {d.id}
                                </span>
                              </button>
                            ))}
                          </div>
                        </div>
                      )}

                      {/* Open Tasks Section */}
                      {person.openTasks.length > 0 && (
                        <div>
                          <span className="text-[10px] font-mono uppercase tracking-wider text-slate-400 block mb-1">
                            Open Deliverables ({person.openTasks.length})
                          </span>
                          <div className="space-y-1 max-h-24 overflow-y-auto pr-1">
                            {person.openTasks.map((t: any) => (
                              <div
                                key={t.id}
                                className="p-1.5 rounded bg-space-950/40 text-[11px] font-sans text-slate-300 flex items-center justify-between gap-2 border border-slate-800/80"
                              >
                                <span className="line-clamp-1">{t.task}</span>
                                <span className="text-[10px] font-mono text-amber-400 flex-shrink-0">
                                  {t.deadline || 'Pending'}
                                </span>
                              </div>
                            ))}
                          </div>
                        </div>
                      )}

                    </div>
                  </div>
                );
              })}
            </div>
          )}
        </div>

        {/* Footer strip */}
        <div className="px-5 py-3 border-t border-slate-800 bg-space-900/60 flex items-center justify-between text-[11px] font-mono text-slate-400">
          <div>
            Briefings automatically recomputed and cached upon memory expansion.
          </div>
          <button
            onClick={onClose}
            className="px-3 py-1 rounded bg-slate-800 hover:bg-slate-700 text-slate-300 transition-colors"
          >
            DISMISS
          </button>
        </div>

      </div>
    </div>
  );
};
